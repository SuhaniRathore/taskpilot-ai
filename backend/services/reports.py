from pathlib import Path
from datetime import datetime
from reportlab.lib.pagesizes import letter
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib import colors
from xml.sax.saxutils import escape
from backend.config import REPORT_DIR

def create_markdown_report(title: str, content: str) -> dict:
    safe_title = "".join(ch if ch.isalnum() or ch in "-_ " else "_" for ch in title).strip()[:80] or "taskpilot-report"
    filename = f"{safe_title.replace(' ', '_')}_{datetime.now().strftime('%Y%m%d_%H%M%S')}.md"
    path = REPORT_DIR / filename
    path.write_text(f"# {title}\n\nGenerated by TaskPilot AI.\n\n{content}\n", encoding="utf-8")
    return {"created": True, "filename": filename, "path": str(path), "content": path.read_text(encoding="utf-8")}

def create_pdf_report(title: str, content: str) -> Path:
    safe_title = "".join(ch if ch.isalnum() or ch in "-_ " else "_" for ch in title).strip()[:80] or "taskpilot-report"
    path = REPORT_DIR / f"{safe_title.replace(' ', '_')}_{datetime.now().strftime('%Y%m%d_%H%M%S')}.pdf"
    styles = getSampleStyleSheet()
    story = [Paragraph(escape(title), styles["Title"]), Spacer(1, 12)]
    for paragraph in content.splitlines():
        story.append(Paragraph(escape(paragraph) or " ", styles["BodyText"]))
        story.append(Spacer(1, 6))
    SimpleDocTemplate(str(path), pagesize=letter).build(story)
    return path
